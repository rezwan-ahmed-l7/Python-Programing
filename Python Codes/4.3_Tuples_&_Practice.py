# Tuple Slicing

tup1 = (1, 2, 3, 4, 5)
result = tup1[1:5]

print(result)

print()
# Tuple Methods

tup2 = (2, 4, 6, 8, 10)

print(tup2.count(2))  # Returns the number of occurrences of a specified value in a tuple
print(tup2.index(6))  # Returns the index of the first occurrence of a specified value in a tuple